# ============================================================
# TEST 8 — OPERATOR VERIFICATION
# ============================================================

def test_operator_is_lte(modern):
    """
    Explicitly verify the critical <= boundary.

    This prevents an accidental modernization from changing:

        <=

    into:

        <
    """

    equal_result = verify_status(
        modern,
        "250.00",
        "250.00",
        "Operator <= boundary"
    )

    return equal_result


# ============================================================
# STATUS VERIFICATION HELPER
# ============================================================

def verify_status(
    modern,
    amount_text: str,
    limit_text: str,
    description: str
) -> bool:

    amount = Decimal(amount_text)
    limit = Decimal(limit_text)

    # Independent COBOL expectation.
    expected = legacy_expected_status(
        amount,
        limit
    )

    # Build modern record.
    record = modern.PaymentRecord(
        payment_id=1,
        account_id=100,
        amount=amount,
        credit_limit=limit,
        status="PENDING",
        customer_name="BRIDGE GUARD TEST"
    )

    # Execute modern business logic.
    actual = modern.evaluate_payment(
        record.amount,
        record.credit_limit
    )

    passed = expected == actual

    print(
        f"{description:<40} | "
        f"LEGACY={expected:<8} | "
        f"MODERN={actual:<8} | "
        f"{'PASS' if passed else 'MISMATCH'}"
    )

    return passed


