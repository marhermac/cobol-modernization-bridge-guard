# ============================================================
# TEST 5 — DECIMAL TYPE
# ============================================================

def test_decimal_representation(modern):
    """
    Monetary values must use Decimal rather than float.
    """

    record = modern.PaymentRecord(
        payment_id=1,
        account_id=100,
        amount=Decimal("500.00"),
        credit_limit=Decimal("500.00"),
        status="PENDING",
        customer_name="BRIDGE GUARD TEST"
    )

    passed = (
        isinstance(record.amount, Decimal)
        and isinstance(record.credit_limit, Decimal)
    )

    print(
        f"{'Decimal monetary representation':<40} | "
        f"{'PASS' if passed else 'MISMATCH'}"
    )

    return passed


