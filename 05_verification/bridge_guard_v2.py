from decimal import Decimal
from pathlib import Path
import importlib.util
import sys


# ============================================================
# PATHS
# ============================================================

ROOT = Path(__file__).resolve().parent

MODERN_FILE = (
    ROOT.parent
    / "04_modernization"
    / "modern_payment_processor.py"
)

# ============================================================
# LOAD MODERN IMPLEMENTATION
# ============================================================

def load_modern_module():
    """Load Bob's generated Python implementation."""

    if not MODERN_FILE.exists():
        raise FileNotFoundError(
            f"Modern implementation not found:\n{MODERN_FILE}"
        )

    spec = importlib.util.spec_from_file_location(
        "modern_payment_processor",
        MODERN_FILE
    )

    if spec is None or spec.loader is None:
        raise ImportError(
            "Could not load modern_payment_processor.py"
        )

    module = importlib.util.module_from_spec(spec)

    # Required for dynamically loaded dataclass modules.
    sys.modules[spec.name] = module

    spec.loader.exec_module(module)

    return module


# ============================================================
# LEGACY BEHAVIOR
# ============================================================

def legacy_expected_status(
    amount: Decimal,
    credit_limit: Decimal
) -> str:
    """
    Independent representation of the COBOL rule.

    COBOL:

        IF HV-AMOUNT <= HV-CREDIT-LIMIT
            APPROVED
        ELSE
            REVIEW
    """

    if amount <= credit_limit:
        return "APPROVED"

    return "REVIEW"


# ============================================================
# TEST 1 — BELOW LIMIT
# ============================================================

def test_below_limit(modern):
    """
    499.99 <= 500.00
    Expected: APPROVED
    """

    return verify_status(
        modern,
        "499.99",
        "500.00",
        "Below credit limit"
    )


