def main():

    print()
    print("=" * 72)
    print("BRIDGE GUARD V2")
    print("Legacy → Modern Behavioral Verification")
    print("=" * 72)
    print()

    # --------------------------------------------------------
    # LOAD
    # --------------------------------------------------------

    print("[1] Loading modern implementation...")

    try:
        modern = load_modern_module()
    except Exception as exc:
        print()
        print("ERROR loading modern implementation:")
        print(exc)
        return 1

    print("    OK")

    # --------------------------------------------------------
    # INTERFACE
    # --------------------------------------------------------

    print()
    print("[2] Checking generated implementation...")

    required = [
        "PaymentRecord",
        "evaluate_payment",
    ]

    for name in required:

        if not hasattr(modern, name):

            print()
            print(
                f"ERROR: generated module does not expose "
                f"'{name}'."
            )

            return 1

    print("    OK")

    # --------------------------------------------------------
    # TESTS
    # --------------------------------------------------------

    print()
    print("[3] Focused behavioral verification")
    print("-" * 72)

    tests = [
        ("BR-02", test_below_limit),
        ("BR-02", test_equal_limit),
        ("BR-03", test_above_limit),
        ("BR-02", test_zero_amount),
        ("DATA", test_decimal_representation),
        ("DATA", test_account_id_present),
        ("DATA", test_status_present),
        ("BR-02", test_operator_is_lte),
    ]

    results = []

    for rule_id, test_function in tests:

        try:
            result = test_function(modern)
        except Exception as exc:

            print(
                f"{rule_id:<7} | "
                f"{test_function.__name__:<35} | "
                f"ERROR: {exc}"
            )

            result = False

        results.append(result)

    # --------------------------------------------------------
    # SUMMARY
    # --------------------------------------------------------

    passed = sum(results)
    total = len(results)

    print()
    print("=" * 72)

    if passed == total:

        print(
            f"RESULT: VERIFIED "
            f"({passed}/{total} focused checks passed)"
        )

        print()
        print(
            "The modern implementation preserves the "
            "tested legacy behavior."
        )

        print()
        print(
            "IMPORTANT: This is focused verification, "
            "not exhaustive equivalence testing."
        )

        print("=" * 72)

        return 0

    print(
        f"RESULT: BLOCKED "
        f"({passed}/{total} checks passed)"
    )

    print()
    print(
        "Behavioral mismatch detected."
    )

    print(
        "The modernization must NOT be accepted."
    )

    print("=" * 72)

    return 1


# ============================================================
